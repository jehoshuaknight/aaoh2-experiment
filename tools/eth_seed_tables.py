"""Write shaders/ethnicity_seeds.slang: the ethnographic model itself (every people's homeland seeds) for
the in-game map, so the shader can draw real zones with natural borders and enclaves, like an atlas.

Per seed, two uints:
  A = lat (10 bits) | lon (11 bits) << 10 | urban (1 bit) << 21 | group (9 bits) << 22
  B = weight x 32 (8 bits) | radius x 8 (8 bits) << 8           (weight up to ~8, radius up to ~32 deg)
Seeds are listed per region (Earth's regions, then Mars's), sorted by group, holding only the peoples
that can win somewhere in or near the region; seedRange(region) gives the slice.

usage: python3 -I eth_seed_tables.py <AstraNovum dir> <tools dir with groups.py> <out .slang>
"""
import sys, os
import numpy as np
from PIL import Image

A, TOOLS, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
sys.path.insert(0, TOOLS)
from groups import EARTH, MARS, FUSION_PARENTS   # noqa: E402

D = os.path.join(A, 'bin/game/data'); T = os.path.join(A, 'bin/game/textures/bodies')

def tsv(p):
    for l in open(p, encoding='utf-8'):
        if l.startswith('#') or not l.strip():
            continue
        yield l.rstrip('\n').split('\t')

keys = [f[0] for f in tsv(os.path.join(D, 'ethnicity/groups.tsv'))]
index = {k: i for i, k in enumerate(keys)}

def unit(lat, lon):
    la, lo = np.radians(lat), np.radians(lon)
    return np.stack([np.cos(la) * np.cos(lo), np.sin(la) * np.ones_like(lo), -np.cos(la) * np.sin(lo)], -1)

def body(name, groups, nreg_expected=None):
    low = name.lower()
    region = {int(f[0]): int(f[1]) for f in tsv(os.path.join(D, low, 'provinces.tsv'))}
    W, H = 512, 256
    ids = np.asarray(Image.open(os.path.join(T, f'{name}_provinces.png')).convert('RGB').resize((W, H), Image.NEAREST)).astype(np.int64)
    ids = ids[..., 0] + ids[..., 1] * 256 + ids[..., 2] * 65536
    lut = np.full(ids.max() + 1, -1); [lut.__setitem__(p, r) for p, r in region.items() if p <= ids.max()]
    R = lut[ids]
    lat = 90 - (np.arange(H) + 0.5) / H * 180; lon = -180 + (np.arange(W) + 0.5) / W * 360
    LON, LAT = np.meshgrid(lon, lat)
    P = unit(LAT, LON)
    seeds = [(g[0], la, lo, w, r) for g in groups for la, lo, w, r in g[4]]
    # Group scores everywhere (as the shader computes them, urban boost at a middling 0.3 light).
    G = sorted({s[0] for s in seeds}); gi = {k: i for i, k in enumerate(G)}
    Sc = np.zeros((len(G), H, W), np.float32)
    for k, la, lo, w, r in seeds:
        d = np.degrees(np.arccos(np.clip(P @ unit(np.array(la), np.array(lo)), -1, 1)))
        boost = (0.45 + 2.2 * 0.3) if k in FUSION_PARENTS else 1.0
        Sc[gi[k]] += w * boost * np.exp(-(d / r) ** 2)
    rank = np.argsort(-Sc, 0)[:3]                         # top three peoples at each point
    nreg = max(region.values()) + 1
    out, start = [], []
    for r in range(nreg):
        m = R == r
        # dilate the region by ~4 degrees so zones run on smoothly across region borders
        mm = m.copy()
        for _ in range(6):
            mm = mm | np.roll(mm, 1, 0) | np.roll(mm, -1, 0) | np.roll(mm, 1, 1) | np.roll(mm, -1, 1)
        winners = set(np.unique(rank[:, mm])) if mm.any() else set()
        # plus every people with a seed (homeland or core) in or near the region, so enclaves always draw
        for k, la, lo, w, rr in seeds:
            y = min(H - 1, max(0, int((90 - la) / 180 * H))); x = min(W - 1, max(0, int((lo + 180) / 360 * W)))
            if mm[y, x]:
                winners.add(gi[k])
        ks = sorted((G[i] for i in winners), key=lambda k: index[k])[:96]
        start.append(len(out))
        for k, la, lo, w, rr in seeds:
            if k in ks:
                pass
        for k in ks:
            for kk, la, lo, w, rr in seeds:
                if kk != k:
                    continue
                # 0.1.20: the seed as a unit vector (10 bits a component), so the shader needs no trigonometry
                v = unit(np.array(la), np.array(lo))
                q = [max(0, min(1023, int(round((c + 1.0) * 511.5)))) for c in v]
                a = q[0] | q[1] << 10 | q[2] << 20
                b = (max(1, min(255, round(w * 32))) | max(1, min(255, round(rr * 8))) << 8
                     | index[k] << 16 | (1 if k in FUSION_PARENTS else 0) << 25)
                out.append((a, b))
    start.append(len(out))
    return nreg, start, out

en, es, ed = body('Earth', EARTH)
mn, ms, md = body('Mars', MARS)
starts = es[:-1] + [len(ed) + x for x in ms]
seeds = ed + md
ranges = [f'uint2({starts[r]}u, {starts[r + 1]}u)' for r in range(len(starts) - 1)]

def sw(fn, vals, default, ret):
    body = '\n'.join(f'    case {i}u: return {v};' for i, v in enumerate(vals))
    return f'{ret} {fn}(uint i)\n{{\n    switch (i)\n    {{\n{body}\n    default: return {default};\n    }}\n}}\n\n'

with open(OUT, 'w', newline='\n') as fh:
    fh.write('// Generated by tools/eth_seed_tables.py from tools/groups*.py. Do not edit.\n')
    fh.write(f'// {len(seeds)} seed entries; Earth {en} regions, Mars {mn} regions (after Earth\'s).\n')
    fh.write('// seedEntry: x = unit vector, 10 bits a component (x | y << 10 | z << 20), y = weight*32 | radius*8 << 8 | group << 16 | urban << 25\n\n')
    fh.write(sw('seedRange', ranges, 'uint2(0u, 0u)', 'uint2'))
    fh.write(sw('seedEntry', [f'uint2({a}u, {b}u)' for a, b in seeds], 'uint2(0u, 0u)', 'uint2'))
lens = [starts[r + 1] - starts[r] for r in range(len(starts) - 1)]
print(f'{len(seeds)} seed entries; per region mean {np.mean(lens):.1f}, max {max(lens)}')

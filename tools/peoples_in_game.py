"""Put the peoples into the game's own windows, through its data files (no engine change):

1. F4 (briefing and history): a "Peoples of 2240" era in data/campaign/history_2240.toml, one entry per
   people (title = the people, text = its written description), dated 2240 so it sits at the end of the
   timeline and passes the loader's checks (date order, nothing after the start year).
2. The province panel: one entry per Earth province in data/earth/cities.tsv, named with the province's
   top three peoples ("Peoples: ... 65% / ... 18% / ... 7%"), placed on a land pixel inside the province
   with a population of 1, so the panel's Cities line shows it.

Idempotent: earlier generated entries are removed first.
usage: python3 -I peoples_in_game.py <AstraNovum dir>
"""
import sys, os, re, unicodedata
import numpy as np
from PIL import Image

A = sys.argv[1]
D = os.path.join(A, 'bin/game/data'); T = os.path.join(A, 'bin/game/textures/bodies')
MARK_H = '# ---- Peoples of 2240 (generated by tools/peoples_in_game.py) ----'

def tsv(p):
    for l in open(p, encoding='utf-8'):
        if l.startswith('#') or not l.strip():
            continue
        yield l.rstrip('\n').split('\t')

def ascii_(s):
    s = unicodedata.normalize('NFKD', s)
    return ''.join(c for c in s if ord(c) < 128)

def toml_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

info = [f for f in tsv(os.path.join(D, 'ethnicity/peoples_info.tsv'))]
groups = {f[0]: f for f in tsv(os.path.join(D, 'ethnicity/groups.tsv'))}

# ---- 1. history_2240.toml
hp = os.path.join(D, 'campaign/history_2240.toml')
h = open(hp, encoding='utf-8').read()
if MARK_H in h:
    h = h[:h.index(MARK_H)].rstrip() + '\n'
ents = []
for f in sorted(info, key=lambda r: ascii_(r[1]).lower()):
    key, name, desc = f[0], f[1], f[-1]
    body = 'Mars' if key.startswith('m_') else 'Earth'
    title = ascii_(re.sub(r'\s*\([^)]*\)', '', name)).strip() + ('' if body == 'Earth' else ' (Mars)')
    ents.append('[[event]]\nyear = 2240\nera = "Peoples of 2240"\ntitle = ' + toml_str(title) + '\ntext = ' + toml_str(ascii_(desc)) + '\nfactions = []\n')
h = h.rstrip() + '\n\n' + MARK_H + '\n# Every people of Earth and Mars, A to Z. Open with F4.\n\n' + '\n'.join(ents)
open(hp, 'w', encoding='utf-8', newline='\n').write(h)

# ---- 2. cities.tsv: a "Peoples:" line per Earth province
cp = os.path.join(D, 'earth/cities.tsv')
raw = open(cp, encoding='utf-8').read()
nl = '\r\n' if '\r\n' in raw else '\n'
lines = [l for l in raw.splitlines() if not l.startswith('Peoples:')]
ids = np.asarray(Image.open(os.path.join(T, 'Earth_provinces.png')).convert('RGB')).astype(np.int64)
ids = ids[..., 0] + ids[..., 1] * 256 + ids[..., 2] * 65536
H, W = ids.shape
water = np.asarray(Image.open(os.path.join(T, 'Earth_water.png')).convert('L').resize((W, H), Image.NEAREST)) > 127
short = {k: ascii_(re.sub(r'\s*\([^)]*\)', '', g[1])).strip() for k, g in groups.items()}
added = 0
for f in tsv(os.path.join(D, 'earth/ethnicity.tsv')):
    pid = int(f[0])
    m = (ids == pid) & ~water
    ys, xs = np.nonzero(m)
    if len(ys) == 0:
        continue
    # the province pixel nearest its centre of mass, so the entry is surely inside it
    cy, cx = ys.mean(), xs.mean()
    j = np.argmin((ys - cy) ** 2 + (xs - cx) ** 2)
    lat = 90 - (ys[j] + 0.5) / H * 180; lon = -180 + (xs[j] + 0.5) / W * 360
    mix = [(kv.split(':')[0], int(kv.split(':')[1])) for kv in f[2].split(';') if kv and not kv.startswith('other')][:3]
    label = 'Peoples: ' + ' / '.join(f'{short.get(k, k)} {v}%' for k, v in mix)
    lines.append(f'{label}\t{lat:.4f}\t{lon:.4f}\t1\t0')
    added += 1
open(cp, 'w', encoding='utf-8', newline='').write(nl.join(lines) + nl)
print(f'history: {len(ents)} peoples in F4; cities.tsv: {added} province lines')

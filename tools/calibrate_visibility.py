"""Make every Earth people hold at least a core on the map: where a people loses at its own homeland, add a
small core seed just strong enough to win there (an enclave). Writes groups_cores.py.
usage: python3 -I calibrate_visibility.py <AstraNovum dir>
"""
import sys, os
import numpy as np
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'groups_cores.py'), 'w').write('CORES = {}\n')
import groups  # noqa: E402  (loads with no cores)
A = sys.argv[1]; T = os.path.join(A, 'bin/game/textures/bodies/')
Image.MAX_IMAGE_PIXELS = None
water = np.asarray(Image.open(T + 'Earth_water.png').convert('L').resize((2048, 1024), Image.NEAREST)) > 127
lights = np.asarray(Image.open(T + 'Earth_lights.jpg').convert('L').resize((2048, 1024), Image.BOX), np.float32) / 255

def unit(la, lo):
    la, lo = np.radians(la), np.radians(lo)
    return np.array([np.cos(la) * np.cos(lo), np.sin(la), -np.cos(la) * np.sin(lo)])
def px(la, lo): return min(1023, max(0, int((90 - la) / 180 * 1024))), min(2047, max(0, int((lo + 180) / 360 * 2048)))
def on_land(la, lo):
    y, x = px(la, lo)
    if not water[y, x]: return la, lo
    for r in range(1, 40):                      # nearest land within ~7 degrees
        for dy in range(-r, r + 1):
            for dx in (-r, r) if abs(dy) != r else range(-r, r + 1):
                yy, xx = y + dy, (x + dx) % 2048
                if 0 <= yy < 1024 and not water[yy, xx]:
                    return 90 - (yy + 0.5) / 1024 * 180, -180 + (xx + 0.5) / 2048 * 360
    return None
def city_at(la, lo):
    y, x = px(la, lo); l = lights[y, x]
    t = np.clip((l - 0.05) / 0.55, 0, 1); return t * t * (3 - 2 * t)

cores = {}
G = list(groups.EARTH)
by = {g[0]: g for g in G}
def state():
    seeds = [(g[0], la, lo, w, r) for g in G for la, lo, w, r in g[4]] + [(k, la, lo, w, r) for k, cs in cores.items() for la, lo, w, r in cs]
    S = np.array([[la, lo, w, r] for _, la, lo, w, r in seeds]); K = np.array([s[0] for s in seeds])
    U = np.stack([unit(la, lo) for la, lo, _, _ in S]); urb = np.array([k in groups.FUSION_PARENTS for k in K])
    return S, K, U, urb
def scores_at(st, la, lo):
    S, K, U, urb = st; c = city_at(la, lo)
    d = np.degrees(np.arccos(np.clip(U @ unit(la, lo), -1, 1)))
    contrib = S[:, 2] * np.where(urb, 0.45 + 2.2 * c, 1.0) * np.exp(-(d / S[:, 3]) ** 2)
    out = {}
    for kk, v in zip(K, contrib): out[kk] = out.get(kk, 0.0) + v
    return out, c
def wins(st, k, la, lo, margin=1.15):
    sc, _ = scores_at(st, la, lo); own = sc.get(k, 0.0); other = max([v for kk, v in sc.items() if kk != k] or [0])
    return own > other * margin
for it in range(9):
    st = state(); losers = []
    for g in G:
        k = g[0]
        pts = [on_land(la, lo) for la, lo, _, _ in g[4]] + [(la, lo) for la, lo, _, _ in cores.get(k, [])]
        if not any(wins(st, k, *p_) for p_ in pts if p_):
            losers.append(k)
    print(f'pass {it + 1}: {len(losers)} peoples hold no spot' + (f' {losers}' if len(losers) < 8 else ''))
    if not losers: break
    # smallest peoples first; each picks the candidate spot where it competes best, then joins the state
    losers.sort(key=lambda k: max(s[2] for s in by[k][4]))
    for k in losers:
        st = state()
        cands = []
        for la, lo, w, r in by[k][4]:
            for rad in (0.0, 0.9, 1.7, 2.6):
                for a in ([0.0] if rad == 0 else np.linspace(0, 2 * np.pi, 8, endpoint=False)):
                    p_ = on_land(la + rad * np.sin(a), lo + rad * np.cos(a) / max(np.cos(np.radians(la)), 0.2))
                    if p_: cands.append(p_)
        best = None
        for la, lo in cands:
            sc, c = scores_at(st, la, lo); own = sc.get(k, 0.0); other = max([v for kk, v in sc.items() if kk != k] or [0])
            boost = (0.45 + 2.2 * c) if k in groups.FUSION_PARENTS else 1.0
            need = max(0.0, other * 1.6 - own) / boost
            if best is None or need < best[0]: best = (need, la, lo)
        if best is None: continue
        need, la, lo = best
        r = 0.45 if k in groups.FUSION_PARENTS else 0.7
        cores[k] = cores.get(k, []) + [(round(float(la), 2), round(float(lo), 2), round(float(need) + 0.05, 3), r)]
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'groups_cores.py'), 'w') as fh:
    fh.write('# Generated by calibrate_visibility.py: core seeds so every people holds at least an enclave.\nCORES = {\n')
    for k, cs in sorted(cores.items()):
        fh.write(f'    {k!r}: {cs!r},\n')
    fh.write('}\n')
print('peoples with cores:', len(cores))
